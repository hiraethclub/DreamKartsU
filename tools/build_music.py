#!/usr/bin/env python3
"""Fetch DreamKarts' music for the port: the same songs as the disc.

Upstream's tools/build_music.py does the download: the manifest
(upstream/assets/music/tracks.txt), the sha256 check and the cache are its
own code, imported here unchanged. Upstream then presses each mp3 into a
CD-DA WAV with ffmpeg; the port plays the mp3s themselves (dr_mp3), so
this script only copies them to music/NN.mp3 (disc order, 01 first) and
measures each song's loudness with tools/music_level.c so the game can
bring them to upstream's TARGET_LUFS as it plays (port/music_levels.h,
checked in, since it only changes when the manifest does).

The download comes from DK_MUSIC_URL (upstream's default,
https://dcvmu.com/dreamkarts/music/) or DK_MUSIC_SOURCE (a folder). It is a
one-off asset fetch at build time (PORT_PLAN.md, Needs Aisling): no game
build ever connects to that server.
"""

from __future__ import annotations

import importlib.util
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UP = ROOT / "upstream"


def upstream_module():
    spec = importlib.util.spec_from_file_location("up_build_music", UP / "tools/build_music.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def level_tool():
    exe = ROOT / "build/tools/music_level"
    src = ROOT / "tools/music_level.c"
    if not exe.exists() or exe.stat().st_mtime < src.stat().st_mtime:
        exe.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["cc", "-O2", "-o", str(exe), str(src), "-I", str(ROOT / "third_party/dr_libs"), "-lm"],
                       check=True)
    return exe


def write_levels(path, rows):
    h = ["/* Generated by tools/build_music.py. Do not edit by hand. */",
         "#ifndef DKU_MUSIC_LEVELS_H", "#define DKU_MUSIC_LEVELS_H", "",
         "/* Per song (music/NN.mp3, disc order): integrated loudness (LUFS) and",
         "   sample peak (dBFS) as measured, and the gain (dB) that brings it to",
         "   upstream's TARGET_LUFS; port/shim/cdda_shim.c limits what would",
         "   clip, as upstream's alimiter does. */",
         f"#define DKU_MUSIC_FILES {len(rows)}",
         f"#define DKU_MUSIC_PEAK_DB {rows[0][3]:.1f}f",
         "static const float dku_music_gain_db[DKU_MUSIC_FILES] = {"
         + ", ".join(f"{g:.2f}f" for _, _, g, _ in rows) + "};",
         "/* As measured:"]
    h += [f"   {i:02d}.mp3 {lufs:6.1f} LUFS, peak {peak:5.1f} dBFS" for i, (lufs, peak, _, _) in enumerate(rows, 1)]
    h += ["*/", "", "#endif", ""]
    text = "\n".join(h)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
        print(f"music: wrote {path.relative_to(ROOT)}")


def main():
    up = upstream_module()
    tracks = up.read_manifest(UP / "assets/music/tracks.txt")
    cache = ROOT / "music/cache"
    out = ROOT / "music"
    url = os.environ.get("DK_MUSIC_URL", up.DEFAULT_URL)
    url = url if url.endswith("/") else url + "/"
    source = os.environ.get("DK_MUSIC_SOURCE")
    tool = level_tool()
    rows = []
    for i, t in enumerate(tracks, 1):
        mp3 = up.fetch(t, cache, url, Path(source) if source else None)
        dest = out / f"{i:02d}.mp3"
        if not dest.exists() or up.sha256_of(dest) != t.sha256:
            shutil.copyfile(mp3, dest)
        res = subprocess.run([str(tool), str(dest)], capture_output=True, text=True, check=True).stdout.split()
        lufs, peak = float(res[0]), float(res[1])
        gain = up.TARGET_LUFS - lufs
        print(f"music: {dest.name} {t.title}: {lufs:6.1f} LUFS, peak {peak:5.1f} dBFS: gain {gain:+.1f} dB")
        rows.append((lufs, peak, gain, up.PEAK_DB))
    write_levels(ROOT / "port/music_levels.h", rows)
    print(f"music: {len(tracks)} songs in {out.relative_to(ROOT)}/")


if __name__ == "__main__":
    sys.exit(main())
